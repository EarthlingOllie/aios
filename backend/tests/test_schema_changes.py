def change(*ops: dict) -> SchemaChange:
    return SchemaChange.model_validate({"ops": list(ops)})


EMPTY = StoreSchema(tables={}, relations=set())


def test_create_table_compiles_to_a_quoted_table_with_an_identity_key_and_comments():
    spec = check(
        change(
            {
                "op": "create_table",
                "name": "contacts",
                "description": "People the user has met",
                "columns": [
                    {"name": "name", "type": "text", "nullable": False},
                    {"name": "met_on", "type": "date", "default": "now"},
                    {"name": "notes", "type": "text", "description": "Anything else"},
                ],
            }
        ),
        EMPTY,
    )

    assert compile_sql(spec) == (
        'CREATE TABLE "data"."contacts" (\n'
        '    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n'
        '    "name" text NOT NULL,\n'
        '    "met_on" date DEFAULT CURRENT_DATE,\n'
        '    "notes" text\n'
        ");\n"
        'COMMENT ON TABLE "data"."contacts" IS \'People the user has met\';\n'
        'COMMENT ON COLUMN "data"."contacts"."notes" IS \'Anything else\';'
    )


