"""Schema change specs: what agents may ask for, checked against a store's schema, and the SQL
they compile to (`aios.datastores.schema_changes`). Pure: no database."""

import pytest

from aios.datastores.schema_changes import (
    AddColumn,
    Column,
    CreateIndex,
    Invalid,
    SchemaChange,
    StoreSchema,
    check,
    compile_sql,
)


def change(*ops: dict) -> SchemaChange:
    return SchemaChange.model_validate({"ops": list(ops)})


EMPTY = StoreSchema(tables={}, relations=set())


def test_create_table_compiles_to_a_quoted_table_with_an_identity_key_and_comments():
    spec = check(
        change(
            {
                "op": "create_table",
                "name": "contacts",
                "description": "People the user has met",
                "columns": [
                    {"name": "name", "type": "text", "nullable": False},
                    {"name": "met_on", "type": "date", "default": "now"},
                    {"name": "notes", "type": "text", "description": "Anything else"},
                ],
            }
        ),
        EMPTY,
    )

    assert compile_sql(spec) == (
        'CREATE TABLE "data"."contacts" (\n'
        '    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n'
        '    "name" text NOT NULL,\n'
        '    "met_on" date DEFAULT CURRENT_DATE,\n'
        '    "notes" text\n'
        ");\n"
        'COMMENT ON TABLE "data"."contacts" IS \'People the user has met\';\n'
        'COMMENT ON COLUMN "data"."contacts"."notes" IS \'Anything else\';'
    )


FISH = StoreSchema(
    tables={"fish": {"id": "bigint", "name": "text", "notes": "jsonb", "weight_kg": "numeric"}},
    relations={"fish", "fish_pkey", "fish_id_seq"},
)


def test_add_column_compiles_to_alter_table_with_its_default_and_comment():
    spec = check(
        change(
            {
                "op": "add_column",
                "table": "fish",
                "column": {
                    "name": "released",
                    "type": "boolean",
                    "nullable": False,
                    "default": False,
                    "description": "Whether it went back",
                },
            }
        ),
        FISH,
    )

    assert compile_sql(spec) == (
        'ALTER TABLE "data"."fish" ADD COLUMN "released" boolean NOT NULL DEFAULT FALSE;\n'
        'COMMENT ON COLUMN "data"."fish"."released" IS \'Whether it went back\';'
    )


def test_an_embedding_column_is_a_vector_marked_as_its_text_columns_embedding():
    spec = check(
        change(
            {
                "op": "create_table",
                "name": "notes",
                "columns": [
                    {"name": "body", "type": "text"},
                    {"name": "body_embedding", "type": "embedding", "embedding_of": "body"},
                ],
            },
            {
                "op": "create_index",
                "table": "notes",
                "columns": ["body_embedding"],
                "method": "hnsw",
            },
        ),
        EMPTY,
    )

    assert compile_sql(spec) == (
        'CREATE TABLE "data"."notes" (\n'
        '    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n'
        '    "body" text,\n'
        '    "body_embedding" "extensions"."vector"(1024)\n'
        ");\n"
        'INSERT INTO "aios"."embedding_columns" (table_name, column_name, source_column)'
        " VALUES ('notes', 'body_embedding', 'body');\n"
        'CREATE INDEX "notes_body_embedding_idx" ON "data"."notes"'
        ' USING hnsw ("body_embedding" "extensions"."vector_cosine_ops");'
    )


@pytest.mark.parametrize(
    ("index", "sql"),
    [
        (
            {"columns": ["name"], "unique": True, "name": "fish_by_name"},
            'CREATE UNIQUE INDEX "fish_by_name" ON "data"."fish" USING btree ("name");',
        ),
        (
            {"columns": ["weight_kg", "name"]},
            'CREATE INDEX "fish_weight_kg_name_idx" ON "data"."fish"'
            ' USING btree ("weight_kg", "name");',
        ),
        (
            {"columns": ["notes"], "method": "gin"},
            'CREATE INDEX "fish_notes_idx" ON "data"."fish" USING gin ("notes");',
        ),
        (
            {"columns": ["name"], "method": "fulltext"},
            'CREATE INDEX "fish_name_idx" ON "data"."fish"'
            " USING gin (to_tsvector('english', \"name\"));",
        ),
    ],
)
def test_create_index_compiles_each_method(index, sql):
    spec = check(change({"op": "create_index", "table": "fish", **index}), FISH)

    assert compile_sql(spec) == sql


def test_a_composite_primary_key_and_typed_defaults():
    spec = check(
        change(
            {
                "op": "create_table",
                "name": "visits",
                "primary_key": ["place", "day"],
                "columns": [
                    {"name": "place", "type": "uuid", "nullable": False, "default": "random"},
                    {"name": "day", "type": "date", "nullable": False, "default": "2026-10-17"},
                    {"name": "at", "type": "timestamptz", "default": "now"},
                    {"name": "count", "type": "integer", "default": 1},
                    {"name": "score", "type": "numeric", "default": "2.50"},
                    {"name": "label", "type": "text", "default": "it's"},
                    {"name": "point", "type": "vector", "dimensions": 3},
                    {"name": "extra", "type": "jsonb"},
                ],
            }
        ),
        EMPTY,
    )

    assert compile_sql(spec) == (
        'CREATE TABLE "data"."visits" (\n'
        '    "place" uuid NOT NULL DEFAULT gen_random_uuid(),\n'
        "    \"day\" date NOT NULL DEFAULT '2026-10-17',\n"
        '    "at" timestamptz DEFAULT now(),\n'
        '    "count" integer DEFAULT 1,\n'
        '    "score" numeric DEFAULT 2.50,\n'
        "    \"label\" text DEFAULT 'it''s',\n"
        '    "point" "extensions"."vector"(3),\n'
        '    "extra" jsonb,\n'
        '    PRIMARY KEY ("place", "day")\n'
        ");"
    )


HOSTILE = 'x"; DROP TABLE data.fish; --'


def test_the_compiler_quotes_hostile_names_and_text_whatever_they_hold():
    """Names that get past the spec's checks can't, but the compiler doesn't count on them."""
    column = Column.model_construct(
        name=HOSTILE,
        type="text",
        dimensions=None,
        embedding_of=None,
        nullable=True,
        default="'); DROP TABLE data.fish; --",
        description="it's'; DROP TABLE data.fish; --",
    )
    spec = SchemaChange.model_construct(
        ops=[
            AddColumn.model_construct(op="add_column", table='fi"sh', column=column),
            CreateIndex.model_construct(
                op="create_index",
                table='fi"sh',
                columns=[HOSTILE],
                method="btree",
                unique=False,
                name='i"dx',
            ),
        ]
    )

    assert compile_sql(spec) == (
        'ALTER TABLE "data"."fi""sh" ADD COLUMN "x""; DROP TABLE data.fish; --" text'
        " DEFAULT '''); DROP TABLE data.fish; --';\n"
        'COMMENT ON COLUMN "data"."fi""sh"."x""; DROP TABLE data.fish; --"'
        " IS 'it''s''; DROP TABLE data.fish; --';\n"
        'CREATE INDEX "i""dx" ON "data"."fi""sh" USING btree ("x""; DROP TABLE data.fish; --");'
    )


@pytest.mark.parametrize(
    "name",
    ["Fish", "1fish", "fish-tank", 'fi"sh', "a" * 64, "", "user", "select", "order", "_fish"],
)
def test_names_must_match_the_pattern_and_not_be_reserved_words(name):
    with pytest.raises(ValueError, match="valid name|reserved word"):
        change({"op": "create_table", "name": name, "columns": [{"name": "x", "type": "text"}]})
    with pytest.raises(ValueError, match="valid name|reserved word"):
        change({"op": "add_column", "table": "fish", "column": {"name": name, "type": "text"}})


@pytest.mark.parametrize(
    "column",
    [
        {"name": "x", "type": "money"},
        {"name": "x", "type": "vector"},
        {"name": "x", "type": "text", "dimensions": 3},
        {"name": "x", "type": "embedding"},
        {"name": "x", "type": "embedding", "embedding_of": "body", "nullable": False},
        {"name": "x", "type": "integer", "default": "1"},
        {"name": "x", "type": "integer", "default": 2**31},
        {"name": "x", "type": "boolean", "default": 1},
        {"name": "x", "type": "date", "default": "yesterday"},
        {"name": "x", "type": "numeric", "default": "NaN"},
        {"name": "x", "type": "jsonb", "default": "{}"},
        {"name": "x", "type": "text", "default": "a\x00b"},
        {"name": "x", "type": "text", "description": "a" * 1001},
        {"name": "x", "type": "text", "sql": "DROP TABLE fish"},
    ],
)
def test_columns_take_only_the_allowlisted_types_and_their_own_defaults(column):
    with pytest.raises(ValueError):
        change({"op": "add_column", "table": "fish", "column": column})


def test_a_spec_has_one_to_twenty_operations_of_the_three_kinds():
    add = {"op": "add_column", "table": "fish", "column": {"name": "x", "type": "text"}}
    with pytest.raises(ValueError):
        change()
    with pytest.raises(ValueError):
        change(*[add] * 21)
    with pytest.raises(ValueError):
        change({"op": "drop_table", "table": "fish"})


def table(name: str, *columns: dict, **more) -> dict:
    return {"op": "create_table", "name": name, "columns": list(columns), **more}


TEXT_X = {"name": "x", "type": "text"}


@pytest.mark.parametrize(
    ("op", "says"),
    [
        (table("fish", TEXT_X), "`data.fish` already exists"),
        (table("fish_pkey", TEXT_X), "`data.fish_pkey` already exists"),
        (table("t", {"name": "id", "type": "uuid"}), "more than one column named id"),
        (table("t", TEXT_X, TEXT_X), "more than one column named x"),
        (table("t", TEXT_X, primary_key=["b"]), "primary key's column `b`"),
        (
            table("t", {"name": "p", "type": "vector", "dimensions": 2}, primary_key=["p"]),
            "can't be in the primary key",
        ),
        (
            table("t", {"name": "e", "type": "embedding", "embedding_of": "missing"}),
            "must be a text column",
        ),
        (
            {"op": "add_column", "table": "eels", "column": TEXT_X},
            "no table `data.eels`",
        ),
        (
            {"op": "add_column", "table": "fish", "column": {"name": "name", "type": "text"}},
            "already has a column `name`",
        ),
        (
            {
                "op": "add_column",
                "table": "fish",
                "column": {"name": "e", "type": "embedding", "embedding_of": "weight_kg"},
            },
            "must be a text column",
        ),
        ({"op": "create_index", "table": "eels", "columns": ["x"]}, "no table `data.eels`"),
        ({"op": "create_index", "table": "fish", "columns": ["gills"]}, "no column `gills`"),
        (
            {"op": "create_index", "table": "fish", "columns": ["name"], "name": "fish_pkey"},
            "`data.fish_pkey` already exists",
        ),
        (
            {"op": "create_index", "table": "fish", "columns": ["name"], "method": "gin"},
            "gin index is for a jsonb column",
        ),
        (
            {"op": "create_index", "table": "fish", "columns": ["name"], "method": "hnsw"},
            "hnsw index is for a vector column",
        ),
        (
            {"op": "create_index", "table": "fish", "columns": ["notes"], "method": "fulltext"},
            "fulltext index is for a text column",
        ),
        (
            {"op": "create_index", "table": "fish", "columns": ["name", "id"], "method": "gin"},
            "a gin index is on one column",
        ),
        (
            {
                "op": "create_index",
                "table": "fish",
                "columns": ["name"],
                "method": "fulltext",
                "unique": True,
            },
            "only a btree index can be unique",
        ),
    ],
)
def test_a_spec_the_stores_schema_doesnt_take_is_invalid(op, says):
    with pytest.raises(Invalid, match="Operation 1") as exc:
        check(change(op), FISH)
    assert says in str(exc.value)


def test_an_hnsw_index_takes_vectors_pgvector_can_index():
    big = StoreSchema(tables={"t": {"v": "vector(2001)"}}, relations={"t"})

    with pytest.raises(Invalid, match="at most 2000 dimensions"):
        check(change({"op": "create_index", "table": "t", "columns": ["v"], "method": "hnsw"}), big)


def test_each_operation_sees_the_ones_before_it():
    ops = [
        table("eels", {"name": "name", "type": "text"}),
        {"op": "add_column", "table": "eels", "column": {"name": "length", "type": "numeric"}},
        {"op": "create_index", "table": "eels", "columns": ["length"]},
        {"op": "create_index", "table": "eels", "columns": ["length"]},
    ]

    checked = check(change(*ops), FISH)

    assert [op.name for op in checked.ops[2:]] == ["eels_length_idx", "eels_length_idx2"]
    with pytest.raises(Invalid, match="Operation 1"):
        check(change(ops[1]), FISH)
