def test_the_data_pages_list_has_pending_requests_first_with_the_run_that_asked(api, agent, queued):
    run, first = start(api, agent, Script(CONTACTS))
    api.post(f"/api/schema-changes/{first['id']}/reject", json={})
    second_run, second = start(api, agent, Script({**CONTACTS, "name": "places"}))

    listed = api.get("/api/schema-changes").json()

    assert [r["id"] for r in listed] == [second["id"], first["id"]]
    assert listed[0]["run"] == {
        "agent_id": agent["id"],
        "run_id": second_run["id"],
        "title": "go",
    }
    assert listed[1]["status"] == "rejected" and listed[1]["note"] is None


@pytest.mark.parametrize("decision", ["approve", "reject"])
def test_a_decision_that_cant_be_queued_is_undone_to_try_again(
    api, agent, queued, monkeypatch, decision
):
    """Rather than leave the request decided with nothing to apply it or resume the run."""
    _, request = start(api, agent, Script(CONTACTS))

    def broker_down(*args):
        raise ConnectionError("Redis is down")

    for task in (worker.apply_schema_change_task, worker.resume_agent_run_task):
        monkeypatch.setattr(task, "delay", broker_down)
    r = api.post(f"/api/schema-changes/{request['id']}/{decision}", json={})

    assert r.status_code == 503
    [listed] = api.get("/api/schema-changes").json()
    assert (listed["status"], listed["decided_at"], listed["can_decide"]) == ("pending", None, True)


def test_a_redelivered_apply_still_resumes_the_run(api, agent, store, queued):
    """The task can stop after applying, before queueing the resume: run again, it doesn't
    apply twice, and queues the resume."""
    script = Script(CONTACTS)
    _, request = start(api, agent, script)
    api.post(f"/api/schema-changes/{request['id']}/approve")
    (task, args) = queued.pop()
    task.run(*args)
    queued.clear()  # the resume it queued is lost

    task.run(*args)

    assert [t for t, _ in queued] == [worker.resume_agent_run_task]
    with use_model(model(script)):
        run_queued(queued)
    (_, outcome), _ = script.results
    assert outcome["status"] == "applied"


def test_a_request_is_decided_once(api, agent, queued):
    _, request = start(api, agent, Script(CONTACTS))

    assert api.post(f"/api/schema-changes/{request['id']}/approve").status_code == 200
    again = api.post(f"/api/schema-changes/{request['id']}/reject", json={})

    assert again.status_code == 409
    assert [task for task, _ in queued] == [worker.apply_schema_change_task]


def test_only_the_stores_owner_can_decide(api, agent, db, new_user, queued):
    _, request = start(api, agent, Script(CONTACTS))
    other: User = new_user()
    app.dependency_overrides[current_user] = lambda: other

    for decision in ("approve", "reject"):
        r = api.post(f"/api/schema-changes/{request['id']}/{decision}", json={})
        assert r.status_code == 404
    assert api.get(f"/api/schema-changes/{request['id']}").status_code == 404
    assert api.get("/api/schema-changes").json() == []
    assert queued == []
    store = db.get(DataStore, request["data_store_id"])
    assert (can_approve(other.id, store), can_approve(store.owner_user_id, store)) == (False, True)


def test_a_workflow_run_cant_wait_on_a_request_yet(api, agent, store, monkeypatch, queued):
    """Its agent nodes would need the workflow to pause, which is to come: the model is told,
    and nothing is requested."""
    monkeypatch.setattr(workflows_api.run_workflow_task, "delay", lambda run_id: None)
    workflow = make_workflow(api, "Builders", [agent_node("build", agent)])
    started = api.post(f"/api/workflows/{workflow['id']}/runs", json={"input": "go"}).json()
    script = Script(CONTACTS)
    with use_model(model(script)):
        asyncio.run(execute_run(started["id"]))

    (name, result), _ = script.results
    assert name == "request_schema_change"
    assert "workflow" in result["error"]
    assert api.get("/api/schema-changes").json() == []
    finished = api.get(f"/api/workflows/{workflow['id']}/runs/{started['id']}").json()
    assert finished["status"] == "succeeded"
