TOOLS = [
    {"key": "request_schema_change", "config": {}},
    {"key": "describe_data", "config": {}},
]

CONTACTS = {
    "op": "create_table",
    "name": "contacts",
    "description": "People the user has met",
    "columns": [{"name": "name", "type": "text", "nullable": False}],
}


@pytest.fixture
def store(db, user) -> DataStore:
    return provisioned(db, data_store_for(user.id))


@pytest.fixture
def agent(api, store) -> dict:
    agent = make_agent(api, "Builder")
    return api.put(f"/api/agents/{agent['id']}", json=agent_body(agent, tools=TOOLS)).json()


@pytest.fixture
def queued(monkeypatch) -> list:
    """The tasks queued, as (task, args), instead of sent to the broker."""
    tasks: list = []
    for task in (worker.apply_schema_change_task, worker.resume_agent_run_task):
        monkeypatch.setattr(task, "delay", lambda *args, task=task: tasks.append((task, args)))
    return tasks


def run_queued(queued: list) -> None:
    """Run the queued tasks (and those they queue) as the workers would."""
    while queued:
        task, args = queued.pop(0)
        task.run(*args)


class Script:
    """The model: asks for `ops` once, then, given the outcome, calls `describe_data` and says
    what it saw. Records each tool result it's given."""

    def __init__(self, *ops: dict):
        self.ops = list(ops)
        self.results: list = []

    async def __call__(self, messages, info):
        results = last_tool_results(messages)
        self.results.extend((m.name, tool_output(m)) for m in results)
        last = results[-1].name if results else None
        if last is None:
            yield ToolCall(
                "request_schema_change", {"ops": self.ops, "reason": "To keep track of people"}
            )
        elif last == "request_schema_change":
            yield ToolCall("describe_data", {})
        else:
            yield "done"


def start(api, agent: dict, script: Script) -> tuple[dict, dict]:
    """A run whose first turn asks for the change; the run, and its request."""
    run = api.post(f"/api/agents/{agent['id']}/runs").json()
    with use_model(model(script)):
        r = api.post(f"/api/agents/{agent['id']}/runs/{run['id']}/chat", json=chat_body("go"))
        assert r.status_code == 200
        assert '"type":"error"' not in r.text
    run = api.get(f"/api/agents/{agent['id']}/runs/{run['id']}").json()
    [request] = run["schema_change_requests"]
    return run, request


def data_tables(store: DataStore) -> list[str]:
    with as_owner(store) as conn:
        rows = conn.execute("SELECT tablename FROM pg_tables WHERE schemaname = 'data'")
        return sorted(r[0] for r in rows)


def test_the_tool_is_in_the_library(api):
    tools = {t["key"]: t for t in api.get("/api/tools").json()}
    assert tools["request_schema_change"]["default_config"] == {}
    [tool] = build_tool("request_schema_change", {})
    assert set(tool.args) == {"ops", "reason"}
    assert "approve" in tool.description


def test_a_request_ends_the_turn_waiting_with_a_card_of_the_exact_sql(api, agent, queued):
    run, request = start(api, agent, Script(CONTACTS))

    assert request["status"] == "pending"
    assert request["reason"] == "To keep track of people"
    assert request["sql"] == (
        'CREATE TABLE "data"."contacts" (\n'
        '    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n'
        '    "name" text NOT NULL\n'
        ");\n"
        'COMMENT ON TABLE "data"."contacts" IS \'People the user has met\';'
    )
    assert request["can_decide"] is True
    assert run["waiting"] is True
    # The card: the tool call, still waiting for its result.
    [call] = [p for m in run["ui_messages"] for p in m["parts"] if p["type"].startswith("tool-")]
    assert call["type"] == "tool-request_schema_change"
    assert call["toolCallId"] == request["tool_call_id"]
    assert call["state"] == "input-available"
    assert queued == []


def test_a_new_message_is_refused_while_the_request_is_pending(api, agent, queued):
    run, _ = start(api, agent, Script(CONTACTS))

    r = api.post(f"/api/agents/{agent['id']}/runs/{run['id']}/chat", json=chat_body("hello?"))

    assert r.status_code == 409
    assert "schema change" in r.json()["detail"]


def test_approving_applies_it_and_the_run_carries_on_seeing_the_table(api, agent, store, queued):
    script = Script(CONTACTS)
    run, request = start(api, agent, script)

    r = api.post(f"/api/schema-changes/{request['id']}/approve")
    assert r.status_code == 200, r.text
    assert r.json()["status"] == "approved"
    with use_model(model(script)):
        run_queued(queued)

    assert data_tables(store) == ["contacts"]
    (_, outcome), (_, described) = script.results
    assert outcome["status"] == "applied"
    assert "data.contacts" in outcome["message"]
    assert ("data", "contacts") in {(t["schema"], t["name"]) for t in described["tables"]}
    run = api.get(f"/api/agents/{agent['id']}/runs/{run['id']}").json()
    assert run["waiting"] is False
    [request] = run["schema_change_requests"]
    assert request["status"] == "applied"
    assert request["resumed_at"] is not None
    assert run["ui_messages"][-1]["parts"][-1] == {"type": "text", "text": "done", "state": "done"}
    # And the run takes messages again.
    with use_model(model(script)):
        r = api.post(f"/api/agents/{agent['id']}/runs/{run['id']}/chat", json=chat_body("ok"))
    assert r.status_code == 200


def test_rejecting_resumes_the_run_with_the_note_and_changes_nothing(api, agent, store, queued):
    script = Script(CONTACTS)
    run, request = start(api, agent, script)

    r = api.post(f"/api/schema-changes/{request['id']}/reject", json={"note": "Use a sheet"})
    assert r.status_code == 200, r.text
    with use_model(model(script)):
        run_queued(queued)

    assert data_tables(store) == []
    (_, outcome), _ = script.results
    assert outcome["status"] == "rejected"
    assert outcome["note"] == "Use a sheet"
    assert "Use a sheet" in outcome["message"]
    [request] = api.get("/api/schema-changes").json()
    assert (request["status"], request["note"]) == ("rejected", "Use a sheet")


def test_a_failed_apply_resumes_the_run_with_the_error(api, agent, store, queued):
    with as_owner(store) as conn:
        conn.execute("CREATE TABLE data.fish (id int)")
        conn.execute("INSERT INTO data.fish VALUES (1)")
    script = Script(
        {"op": "add_column", "table": "fish", "column": {"name": "kg", "type": "numeric"}},
        {
            "op": "add_column",
            "table": "fish",
            "column": {"name": "n", "type": "text", "nullable": False},
        },
    )
    _, request = start(api, agent, script)

    api.post(f"/api/schema-changes/{request['id']}/approve")
    with use_model(model(script)):
        run_queued(queued)

    (_, outcome), _ = script.results
    assert outcome["status"] == "failed"
    assert "null values" in outcome["error"]
    with as_owner(store) as conn:
        columns = conn.execute(
            "SELECT column_name FROM information_schema.columns WHERE table_name = 'fish'"
        ).fetchall()
    assert columns == [("id",)]


