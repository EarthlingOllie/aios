import { expect, test, type Locator, type Page } from "@playwright/test";

import { fakeApi, type FakeApi } from "./fake-api";

/**
 * Schema change requests: the approval card at the agent's tool call in its chat, and the Data
 * page's Changes section, where the same requests are decided.
 */

const card = (scope: Page | Locator, summary = "Create table data.contacts") =>
  scope.getByRole("region", { name: `Schema change: ${summary}` });

const userMessage = (text: string) => ({
  id: `u-${text}`,
  role: "user",
  parts: [{ type: "text", text }],
});

/** A run whose turn ended asking for a table: the call waits for its result. */
function waitingRun(api: FakeApi) {
  const agent = api.addAgent("Builder");
  const run = api.addAgentRun(agent, "Track my contacts", 3);
  run.ui_messages = [
    userMessage("Track my contacts"),
    {
      id: "a1",
      role: "assistant",
      parts: [
        { type: "step-start" },
        { type: "text", text: "I'll need a table for that.", state: "done" },
        {
          type: "tool-request_schema_change",
          toolCallId: "call_1",
          state: "input-available",
          input: { ops: [], reason: "To keep track of the people you meet" },
        },
      ],
    },
  ];
  const request = api.addSchemaChange({ run_id: run.id, tool_call_id: "call_1" });
  return { agent, run, request };
}

const carriedOn = [
  {
    id: "a2",
    role: "assistant",
    parts: [{ type: "step-start" }, { type: "text", text: "The contacts table is ready.", state: "done" }],
  },
];

test("a run's turn ends with a card of the exact SQL, and waits for a decision", async ({ page }) => {
  const api = await fakeApi(page);
  const { agent, run } = waitingRun(api);

  await page.goto(`/agents/${agent.id}/runs/${run.id}`);

  await expect(card(page)).toContainText("Waiting for you");
  await expect(card(page)).toContainText("To keep track of the people you meet");
  await expect(card(page).getByLabel("SQL")).toHaveText(
    'CREATE TABLE "data"."contacts" (\n    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n    "name" text NOT NULL\n);',
  );
  await expect(page.getByRole("status", { name: "Waiting" })).toContainText(
    "waiting for you to approve or reject",
  );
  await page.locator("#run-input").fill("hello?");
  await expect(page.locator("form:has(#run-input) button[type=submit]")).toBeDisabled();
});

test("approving in the chat applies it, and the run carries on", async ({ page }) => {
  const api = await fakeApi(page);
  const { agent, run, request } = waitingRun(api);
  await page.goto(`/agents/${agent.id}/runs/${run.id}`);

  await card(page).getByRole("button", { name: "Approve" }).click();

  await expect(card(page)).toContainText("Applying");
  await expect(card(page).getByRole("button", { name: "Approve" })).toHaveCount(0);
  expect(api.writes).toContainEqual(["POST", `/api/schema-changes/${request.id}/approve`, null]);

  api.finishSchemaChange(request.id, { status: "applied", messages: carriedOn });

  await expect(page.getByText("The contacts table is ready.")).toBeVisible();
  await expect(card(page)).toContainText("Applied to your data store.");
  await expect(page.getByRole("status", { name: "Waiting" })).toHaveCount(0);
  await page.locator("#run-input").fill("thanks");
  await expect(page.locator("form:has(#run-input) button[type=submit]")).toBeEnabled();
});

test("a run that carries on into another request shows that request's card", async ({ page }) => {
  const api = await fakeApi(page);
  const { agent, run, request } = waitingRun(api);
  await page.goto(`/agents/${agent.id}/runs/${run.id}`);
  await card(page).getByRole("button", { name: "Approve" }).click();
  await expect(card(page)).toContainText("Applying");

  // The resumed turn asks for an index, and waits again: the run never stops waiting.
  api.addSchemaChange({
    run_id: run.id,
    tool_call_id: "call_2",
    summary: "Create index contacts_name_idx on data.contacts",
  });
  api.finishSchemaChange(request.id, {
    status: "applied",
    messages: [
      {
        id: "a2",
        role: "assistant",
        parts: [
          { type: "step-start" },
          { type: "text", text: "Now an index.", state: "done" },
          {
            type: "tool-request_schema_change",
            toolCallId: "call_2",
            state: "input-available",
            input: { ops: [], reason: "Faster lookups" },
          },
        ],
      },
    ],
  });

  const index = card(page, "Create index contacts_name_idx on data.contacts");
  await expect(index).toContainText("Waiting for you");
  await expect(index.getByRole("button", { name: "Approve" })).toBeVisible();
  await expect(card(page)).toContainText("Applied to your data store.");
});

test("rejecting with a note sends the note, and the run carries on", async ({ page }) => {
  const api = await fakeApi(page);
  const { agent, run, request } = waitingRun(api);
  await page.goto(`/agents/${agent.id}/runs/${run.id}`);

  await card(page).getByRole("button", { name: "Reject…" }).click();
  await card(page).getByLabel("Note for the agent (optional)").fill("Use a spreadsheet instead");
  await card(page).getByRole("button", { name: "Reject", exact: true }).click();

  await expect(card(page)).toContainText("Rejected: Use a spreadsheet instead");
  expect(api.writes).toContainEqual([
    "POST",
    `/api/schema-changes/${request.id}/reject`,
    { note: "Use a spreadsheet instead" },
  ]);
  api.finishSchemaChange(request.id, { messages: carriedOn });
  await expect(page.getByText("The contacts table is ready.")).toBeVisible();
});

test("a failed apply says why on the card", async ({ page }) => {
  const api = await fakeApi(page);
  const { agent, run, request } = waitingRun(api);
  await page.goto(`/agents/${agent.id}/runs/${run.id}`);
  await card(page).getByRole("button", { name: "Approve" }).click();
  await expect(card(page)).toContainText("Applying");

  api.finishSchemaChange(request.id, {
    status: "failed",
    error: 'column "name" of relation "contacts" contains null values',
  });

  await expect(card(page)).toContainText(
    'Applying it failed, and nothing changed: column "name" of relation "contacts" contains null values',
  );
});

test("the Changes section lists pending requests first, with the run that asked", async ({ page }) => {
  const api = await fakeApi(page);
  const { agent, run } = waitingRun(api);
  api.addSchemaChange({
    summary: "Add column email to data.contacts",
    status: "rejected",
    note: "Not yet",
    decided_at: "2026-10-14T10:00:00Z",
    resumed_at: "2026-10-14T10:00:01Z",
  });
  await page.goto("/data/changes");

  const pending = page.getByRole("region", { name: "Pending changes" });
  const history = page.getByRole("region", { name: "Change history" });
  await expect(card(pending)).toContainText("To keep track of the people you meet");
  await expect(history).toContainText("Add column email to data.contacts");
  await expect(history).toContainText("Rejected: Not yet");
  await expect(history.getByRole("button", { name: "Approve" })).toHaveCount(0);
  // The history keeps each one's SQL folded away, a click from view.
  await expect(history.getByLabel("SQL")).toBeHidden();
  await history.getByText("Show the SQL").click();
  await expect(history.getByLabel("SQL")).toBeVisible();
  await expect(pending.getByLabel("SQL")).toBeVisible();

  await pending.getByRole("link", { name: "From run “Track my contacts”" }).click();
  await expect(page).toHaveURL(`/agents/${agent.id}/runs/${run.id}`);
});

test("deciding from the Changes section moves the request to the history", async ({ page }) => {
  const api = await fakeApi(page);
  const { request } = waitingRun(api);
  await page.goto("/data/changes");

  await card(page).getByRole("button", { name: "Approve" }).click();

  const history = page.getByRole("region", { name: "Change history" });
  await expect(history).toContainText("Applying");
  await expect(page.getByRole("region", { name: "Pending changes" })).toContainText(
    "No changes are waiting.",
  );
  api.finishSchemaChange(request.id, { status: "applied" });
  await expect(history).toContainText("Applied to your data store.");
});

test("the history shows expired and cancelled requests, with no controls", async ({ page }) => {
  const api = await fakeApi(page);
  api.addSchemaChange({
    summary: "Create table data.places",
    status: "expired",
    decided_at: "2026-10-14T10:00:00Z",
    resumed_at: "2026-10-14T10:00:01Z",
  });
  api.addSchemaChange({
    summary: "Create table data.things",
    status: "cancelled",
    decided_at: "2026-10-15T10:00:00Z",
    resumed_at: "2026-10-15T10:00:00Z",
  });
  await page.goto("/data/changes");

  const history = page.getByRole("region", { name: "Change history" });
  const expired = history.getByRole("region", { name: "Schema change: Create table data.places" });
  const cancelled = history.getByRole("region", { name: "Schema change: Create table data.things" });
  await expect(expired).toContainText("Expired");
  await expect(expired).toContainText("so it expired, which counts as rejected. Nothing changed.");
  await expect(expired).toContainText(/Expired \w/);
  await expect(cancelled).toContainText("Cancelled: the run that asked was deleted or stopped.");
  await expect(cancelled).toContainText(/Cancelled \w/);
  await expect(history.getByRole("button", { name: "Approve" })).toHaveCount(0);
  await expect(page.getByRole("region", { name: "Pending changes" })).toContainText(
    "No changes are waiting.",
  );
});

test("a request the user may not decide has no controls", async ({ page }) => {
  const api = await fakeApi(page);
  api.addSchemaChange({ decider: false });
  await page.goto("/data/changes");

  await expect(card(page)).toBeVisible();
  await expect(card(page).getByRole("button")).toHaveCount(0);
});
